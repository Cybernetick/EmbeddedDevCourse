void oled_send_cmd(i2c_master_dev_handle_t device_handle, struct command_t command) {
    size_t command_size = sizeof(command.command) + command.argc * sizeof(command.args[0]) + 1;
    uint8_t buf[command_size];
    buf[0] = 0x00;
    buf[1] = command.command;
    for (int i = 0; i < command.argc; i++) {
        buf[i + 2] = command.args[i];
    }
    ESP_ERROR_CHECK(i2c_master_transmit(device_handle, buf, sizeof(buf), 100));
}

void oled_init(i2c_master_dev_handle_t device_handle) {
    size_t commands_count = sizeof(init_commands) / sizeof(init_commands[0]);
    for (int i = 0; i < commands_count; i++) {
        oled_send_cmd(device_handle, init_commands[i]);
    }
}

void oled_clear(i2c_master_dev_handle_t device_handle) {
    struct command_t set_column_address_command = {0x21, 2, {0x00, 0x7F} };
    oled_send_cmd(device_handle, set_column_address_command);
    struct command_t set_page_address_command = { 0x22, 2, { 0x00, 0x07 } };
    oled_send_cmd(device_handle, set_page_address_command);
    uint8_t clear_buffer_command[1025];
    clear_buffer_command[0] = 0x40;
    for (int i = 1; i < 1025; i++) {
        clear_buffer_command[i] = 0x00;
    }
    ESP_ERROR_CHECK(i2c_master_transmit(device_handle, clear_buffer_command, sizeof(clear_buffer_command), 200));
}

void oled_draw_time(i2c_master_dev_handle_t device_handle, uint8_t hours, uint8_t minutes, uint8_t seconds) {
    struct command_t set_column_address_command = {0x21, 2, {0x14, 0x6B} };
    oled_send_cmd(device_handle, set_column_address_command);
    struct command_t set_page_address_command = { 0x22, 2, { 0x04, 0x05 } };
    oled_send_cmd(device_handle, set_page_address_command);

    const uint8_t font_header   = 4;
    const uint8_t font_width    = 11;
    const uint8_t font_first    = 0x20;
    const uint8_t bytes_per_char = 22;

    uint8_t chars[DISPLAY_NUM_CHARS] = {
        '0' + hours   / 10, '0' + hours   % 10, ':',
        '0' + minutes / 10, '0' + minutes % 10, ':',
        '0' + seconds / 10, '0' + seconds % 10,
    };

    uint8_t buf[1 + DISPLAY_NUM_CHARS * font_width * 2];
    buf[0] = 0x40;

    for (int c = 0; c < DISPLAY_NUM_CHARS; c++) {
        uint16_t char_offset = font_header + (chars[c] - font_first) * bytes_per_char;
        for (int b = 0; b < font_width; b++) {
            buf[1 + c * font_width + b] = courier_new_font11x16_digits[char_offset + b];
        }
    }

    for (int c = 0; c < DISPLAY_NUM_CHARS; c++) {
        uint16_t char_offset = font_header + (chars[c] - font_first) * bytes_per_char;
        for (int b = 0; b < font_width; b++) {
            buf[1 + DISPLAY_NUM_CHARS * font_width + c * font_width + b] = courier_new_font11x16_digits[char_offset + font_width + b];
        }
    }

    ESP_ERROR_CHECK(i2c_master_transmit(device_handle, buf, sizeof(buf), 200));
}

void oled_draw_date(i2c_master_dev_handle_t device_handle, uint8_t dom, uint8_t month, uint16_t year) {
    struct command_t set_column_address_command = {0x21, 2, {0x32, 0x64} };
    oled_send_cmd(device_handle, set_column_address_command);
    struct command_t set_page_address_command = { 0x22, 2, { 0x07, 0x07 } };
    oled_send_cmd(device_handle, set_page_address_command);

    const uint8_t font_header   = 4;
    const uint8_t font_width    = 5;
    const uint8_t font_first    = 0x20;
    const uint8_t bytes_per_char = 5;

    uint8_t chars[10] = {
            '0' + dom   / 10, '0' + dom   % 10, '.',
            '0' + month   / 10, '0' + month   % 10, '.',
            '0' + year / 1000, '0' + (year / 100) % 10, '0' + (year / 10) % 10, '0' + year % 10
    };

    uint8_t buf[1 + 10 * font_width];
    buf[0] = 0x40;

    for (int c = 0; c < 10; c++) {
        uint16_t char_offset = font_header + (chars[c] - font_first) * bytes_per_char;
        for (int b = 0; b < font_width; b++) {
            buf[1 + c * font_width + b] = ssd1306xled_font5x7_AB[char_offset + b];
        }
    }

    ESP_ERROR_CHECK(i2c_master_transmit(device_handle, buf, sizeof(buf), 200));
}